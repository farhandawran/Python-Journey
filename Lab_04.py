        "    \"\"\"Recursive Depth-Limited Search.\n",
        "    Returns ('found', path), ('cutoff', None) or ('failure', None).\"\"\"\n",
        "    visited_order.append(node)\n",
        "    path.append(node)\n",
        "\n",
        "    if node == goal:\n",
        "        return 'found', path\n",
        "    if limit == 0:\n",
